export const STATIONS = raw.map(([year, albumZh, albumEn, song, scene, style, gag, palette], i) => {
  const n = i + 1;
  return {
    n,
    id: `s${String(n).padStart(2, '0')}`,
    year,
    age: 21 + (year - 2000),
    albumZh,
    albumEn,
    enChecked: false,
    song,
    scene,
    style,
    gag,
    palette,
    player: n <= 5 ? 'cassette' : n <= 12 ? 'cd' : 'phone',
  };
});

export const stationByN = (n) => STATIONS[n - 1];

/** 年龄 → 档位 A/B/C/D */
export function tierOf(age) {
  if (age <= 24) return 'A';
  if (age <= 29) return 'B';
  if (age <= 37) return 'C';
  return 'D';
}
